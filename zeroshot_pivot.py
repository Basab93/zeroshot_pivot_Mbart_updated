class ProcrustesAlignment:
    """
    Implements Procrustes analysis for cross-lingual embedding alignment
    This creates the unified semantic space claimed in the paper
    """
    def __init__(self, embedding_dim=512):
        self.embedding_dim = embedding_dim
        self.alignment_matrix = None
        self.source_mean = None
        self.target_mean = None

    def compute_alignment(self, src_embeddings, tgt_embeddings):
        """
        Compute Procrustes alignment matrix between embedding spaces
        """
        # Center the embeddings
        self.source_mean = src_embeddings.mean(axis=0, keepdims=True)
        self.target_mean = tgt_embeddings.mean(axis=0, keepdims=True)

        src_centered = src_embeddings - self.source_mean
        tgt_centered = tgt_embeddings - self.target_mean

        # Compute covariance matrix
        covariance = src_centered.T @ tgt_centered

        # SVD for Procrustes
        U, S, Vt = np.linalg.svd(covariance)
        self.alignment_matrix = U @ Vt

        # Compute quality metrics
        alignment_quality = np.sum(S) / (np.linalg.norm(src_centered) * np.linalg.norm(tgt_centered))

        return self.alignment_matrix, alignment_quality

    def align_embeddings(self, embeddings):
        """Apply alignment transformation"""
        if self.alignment_matrix is not None:
            centered = embeddings - self.source_mean
            aligned = centered @ self.alignment_matrix
            return aligned + self.target_mean
        return embeddings

