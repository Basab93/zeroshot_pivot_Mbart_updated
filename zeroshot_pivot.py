    inputs = tokenizer(tagged, return_tensors="pt", truncation=True, max_length=128, padding=True)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_length=128,
            num_beams=5,
            early_stopping=True,
            no_repeat_ngram_size=3
        )

