    # Verify output is in Assamese (optional post-processing)
    detector = OffTargetDetector(tokenizer)
    detection = detector.detect_off_target(text, translation)

    if detection['is_off_target']:
        print(f"⚠️ Warning: Possible off-target translation detected")

    return translation, detection

