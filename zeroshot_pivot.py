class LanguageAwareTagging:
    """
    Implements sophisticated language tagging to reduce off-target errors
    This is one of your key contributions
    """
    def __init__(self, tokenizer, model):
        self.tokenizer = tokenizer
        self.model = model
        self.language_tokens = {
            'en': '>>eng<<',  # English (source)
            'bn': '>>ben<<',  # Bengali (pivot)
            'as': '>>asm<<'   # Assamese (target)
        }

        # Verify tokens exist
        self.token_ids = {}
        for lang, token in self.language_tokens.items():
            if token in tokenizer.get_vocab():
                self.token_ids[lang] = tokenizer.convert_tokens_to_ids(token)
                print(f"✅ {lang} token '{token}' found at ID: {self.token_ids[lang]}")
            else:
                print(f"⚠️ {lang} token '{token}' not found, will need to add")

        # Add missing English token if needed
        if 'en' not in self.token_ids:
            self._add_english_token()

    def _add_english_token(self):
        """Add English token to tokenizer and resize embeddings"""
        print("\n   Adding missing English token '>>eng<<' to vocabulary...")
        self.tokenizer.add_tokens(['>>eng<<'])
        self.model.resize_token_embeddings(len(self.tokenizer))
        self.token_ids['en'] = self.tokenizer.convert_tokens_to_ids('>>eng<<')
        print(f"   ✅ Added '>>eng<<' at ID: {self.token_ids['en']}")

    def prepare_input_with_tags(self, text, source_lang='en', target_lang='as', strategy='explicit'):
        """
        Prepare input with explicit language tags
        Multiple tagging strategies as per paper
        """
        if strategy == 'explicit':
            # Strategy 1: Explicit target language prefix (baseline)
            tagged_input = f"{self.language_tokens[target_lang]} {text}"

        elif strategy == 'dual':
            # Strategy 2: Dual tags (source + target) - Your contribution
            tagged_input = f"{self.language_tokens[source_lang]} {self.language_tokens[target_lang]} {text}"

        elif strategy == 'contextual':
            # Strategy 3: Contextual tagging with language emphasis
            tagged_input = f"{self.language_tokens[source_lang]} translate to {self.language_tokens[target_lang]}: {text}"

        elif strategy == 'hierarchical':
            # Strategy 4: Hierarchical tags showing language relationship
            tagged_input = f"{self.language_tokens[source_lang]}->{self.language_tokens[target_lang]} {text}"

        return tagged_input

    def compare_tagging_strategies(self, test_sentences):
        """
        Compare different tagging strategies without attention
        """
        strategies = ['explicit', 'dual', 'contextual', 'hierarchical']
        results = defaultdict(dict)

