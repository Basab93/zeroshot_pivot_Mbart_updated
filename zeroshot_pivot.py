# Procrustes alignment
print("\n2. Applying Procrustes alignment...")

def procrustes_align(src_embs, tgt_embs):
    """Align source embeddings to target space"""
    # Center
    src_centered = src_embs - src_embs.mean(axis=0)
    tgt_centered = tgt_embs - tgt_embs.mean(axis=0)

    # Compute alignment matrix
    covariance = src_centered.T @ tgt_centered
    U, _, Vt = np.linalg.svd(covariance)
    W = U @ Vt

    # Apply alignment
    src_aligned = (src_centered @ W) + tgt_embs.mean(axis=0)
    return src_aligned

