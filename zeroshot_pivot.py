class OffTargetDetector:
    """
    Detects and prevents off-target translations
    """
    def __init__(self, tokenizer, target_lang='as'):
        self.tokenizer = tokenizer
        self.target_lang = target_lang
        self.target_token = f">>{target_lang}<<"

        # Common Assamese characters (Unicode range for Assamese/Bengali script)
        self.assamese_unicode_range = range(0x980, 0x9FF)  # Bengali/Assamese script range

    def is_assamese_text(self, text):
        """Check if text is primarily in Assamese script"""
        if not text:
            return False

        assamese_chars = 0
        total_chars = 0

        for char in text:
            if ord(char) in self.assamese_unicode_range:
                assamese_chars += 1
            if char.isalpha():
                total_chars += 1

        if total_chars == 0:
            return False

        return (assamese_chars / total_chars) > 0.7

    def detect_off_target(self, source, prediction, target_lang='as'):
        """
        Detect if translation is off-target (wrong language)
        """
        # Check if prediction is in target language script
        is_correct_script = self.is_assamese_text(prediction)

        # Check if prediction contains English words (potential off-target)
        words = prediction.split()
        if not words:
            return {
                'is_off_target': False,
                'off_target_score': 0,
                'is_assamese_script': is_correct_script,
                'english_word_ratio': 0
            }

        english_words = sum(1 for word in words
                          if word and all(ord(c) < 128 for c in word if c.isalpha()))

        off_target_score = 0
        if not is_correct_script:
            off_target_score += 0.7
        if english_words > len(words) * 0.3:  # >30% English words
            off_target_score += 0.3

        return {
            'is_off_target': off_target_score > 0.5,
            'off_target_score': off_target_score,
            'is_assamese_script': is_correct_script,
            'english_word_ratio': english_words / max(1, len(words))
        }

